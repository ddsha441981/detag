//! Shared test context (P0-092, E0.10): one struct every suite
//! builds its fixtures from — pg (migrated), redis, MinIO bucketed —
//! with per-test isolation and parallel safety.
//!
//! Two ways to get one:
//!
//! - [`TestCtx::new()`] — from the environment (native services on
//!   this VM, compose in CI): creates a fresh scratch database
//!   (`detag_test_<uuid-v7-hex>`, all migrations applied), a unique
//!   redis key namespace, and a unique S3 bucket. The bucket is
//!   best-effort: on this VM there is no MinIO, so `s3_ready` is
//!   false and the bucket is only a name — tests that need storage
//!   assert `s3_ready()` or skip (the storage crate's own live test
//!   is the bucketed proof here; CI's containers leg proves it
//!   end to end).
//! - [`TestCtx::containers()`] — the same, but postgres:16, redis:7
//!   and quay.io/minio/minio start in testcontainers first (docker only;
//!   callers env-gate it on `PF_TEST_CONTAINERS=1`, CI does). The
//!   bucket IS created here, so `s3_ready()` is true.
//!
//! Isolation is per-test-database for pg (the strongest form — no
//! shared rows, no cleanup queries), a per-test key namespace for
//! redis (`testkit:<uuid>:` prefix — callers build keys with
//! [`TestCtx::redis_key`]), and a per-test bucket for S3. Parallel
//! tests never share a name, so they never collide; the suite runs
//! `cargo test`'s default parallel threads against one pg/redis.
//!
//! Call [`TestCtx::close`].await when done: it drops the scratch
//! database and (best-effort) the bucket. There is no `Drop`
//! cleanup — async drop does not exist, and a spawned cleanup task
//! would race the test runtime shutting down — so a forgotten close
//! leaks a scratch DB. That is harmless (dev-only, a few KB) but
//! untidy; every test in the suite closes its ctx.
//!
//! The api harness (`apps/api/tests/common`) does NOT use the
//! per-test database: its tests already isolate by unique rows
//! (unique emails) against one shared scratch DB, and rebasing it
//! would leak a DB per test with no reliable Drop. It still carries
//! its own inline container definitions for now — deduplicating it
//! onto [`start_containers`]/[`ensure_bucket`] is a follow-up, not
//! part of this ticket (its `TestFixtures` shape differs: one
//! shared scratch DB, not per-test DBs).
//!
//! Test helper, not library code: setup failures panic with a
//! message naming what must be running (same style as the api
//! harness and the core live tests).

use detag_core::{
    config::Settings,
    db::{connect_lazy, DbPool, PoolConfig},
    migrate::migrate_up,
};
use std::path::PathBuf;
use testcontainers::{runners::AsyncRunner, ContainerAsync, GenericImage, ImageExt};
use uuid::Uuid;

/// A unique suffix for per-test names: 32 lowercase hex chars
/// (uuid v7, no hyphens — valid in a Postgres identifier, an S3
/// bucket name and a redis key prefix alike).
pub fn unique_suffix() -> String {
    Uuid::now_v7().simple().to_string()
}

/// Postgres database name for one test: `detag_test_<hex>`.
/// 43 chars, well inside the 63-byte identifier limit.
pub fn test_database_name() -> String {
    format!("detag_test_{}", unique_suffix())
}

/// S3 bucket name for one test: `detag-test-<hex>`. S3 names are
/// lowercase letters, digits and hyphens only — the hex suffix
/// qualifies.
pub fn test_bucket_name() -> String {
    format!("detag-test-{}", unique_suffix())
}

/// Redis key namespace for one test: `testkit:<hex>:`.
pub fn test_redis_prefix() -> String {
    format!("testkit:{}:", unique_suffix())
}

fn migrations_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("..")
        .join("migrations")
}

/// The name is generated by us (uuid hex), never user input — but
/// DDL interpolates it into a string, so assert the shape before
/// it reaches SQL (same rule as the seed's `AssertSqlSafe`).
fn assert_safe_ident(name: &str) {
    assert!(
        !name.is_empty()
            && name
                .chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
            && name.chars().next().unwrap().is_ascii_lowercase(),
        "testkit: unsafe identifier for DDL: {name}"
    );
}

/// Replace the database in a Postgres URL, keeping user, host, port
/// and query string; only the name changes.
fn replace_database(base_url: &str, db: &str) -> String {
    let (head, query) = match base_url.split_once('?') {
        Some((head, query)) => (head, Some(query)),
        None => (base_url, None),
    };
    let base = match head.rfind('/') {
        Some(idx) => &head[..idx],
        None => head,
    };
    match query {
        Some(query) => format!("{base}/{db}?{query}"),
        None => format!("{base}/{db}"),
    }
}

async fn create_database(admin_url: &str, db: &str) {
    use sqlx::Connection as _;
    assert_safe_ident(db);
    let mut admin = sqlx::PgConnection::connect(admin_url).await.unwrap_or_else(|err| {
        panic!("testkit: Postgres must be up on {admin_url} (native `just dev` or compose) — see DOCKER-001: {err}")
    });
    // `AssertSqlSafe` is the audited escape hatch (same as the
    // migrate example's reset arm): the only interpolated value is
    // `db`, which `assert_safe_ident` has restricted to
    // [a-z0-9_] starting with a letter (no quotes, spaces, or
    // semicolons), so no injection is possible through it.
    let sql = format!("CREATE DATABASE \"{db}\"");
    sqlx::query(sqlx::AssertSqlSafe(sql.as_str()))
        .execute(&mut admin)
        .await
        .unwrap_or_else(|err| panic!("testkit: CREATE DATABASE {db}: {err}"));
}

async fn drop_database(admin_url: &str, db: &str) {
    use sqlx::Connection as _;
    assert_safe_ident(db);
    let Ok(mut admin) = sqlx::PgConnection::connect(admin_url).await else {
        return; // best-effort cleanup: a down server leaks the DB, nothing to do
    };
    // Terminate backends first: the ctx pool is closed by then, but
    // a stray connection would block the DROP. Same audited
    // `AssertSqlSafe` as above — `db` is the asserted identifier.
    let terminate =
        format!("SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = '{db}'");
    let _ = sqlx::query(sqlx::AssertSqlSafe(terminate.as_str()))
        .execute(&mut admin)
        .await;
    let drop = format!("DROP DATABASE IF EXISTS \"{db}\"");
    let _ = sqlx::query(sqlx::AssertSqlSafe(drop.as_str()))
        .execute(&mut admin)
        .await;
}

/// A raw S3 client for bucket setup (bucket creation is an ops
/// concern — the provider deliberately has no create_bucket; same
/// pattern as the storage live test).
pub fn s3_client(endpoint: &str, access_key: &str, secret_key: &str) -> aws_sdk_s3::Client {
    let creds =
        aws_sdk_s3::config::Credentials::new(access_key, secret_key, None, None, "detag-testkit");
    let sdk_config = aws_sdk_s3::config::Builder::new()
        .behavior_version(aws_sdk_s3::config::BehaviorVersion::latest())
        .region(aws_sdk_s3::config::Region::new("us-east-1"))
        .credentials_provider(creds)
        .endpoint_url(endpoint)
        .force_path_style(true)
        .build();
    aws_sdk_s3::Client::from_conf(sdk_config)
}

/// Create `bucket` on `endpoint`, retrying while MinIO warms up.
/// Returns false when the endpoint never answers (no MinIO here) —
/// the caller decides whether that is a skip or a failure.
pub async fn ensure_bucket(
    endpoint: &str,
    access_key: &str,
    secret_key: &str,
    bucket: &str,
    attempts: u32,
) -> bool {
    let client = s3_client(endpoint, access_key, secret_key);
    for _ in 0..attempts {
        match client.create_bucket().bucket(bucket).send().await {
            Ok(_) => return true,
            Err(_) => tokio::time::sleep(std::time::Duration::from_millis(500)).await,
        }
    }
    false
}

/// Delete every object in `bucket`, then the bucket itself.
/// Best-effort: any failure is swallowed (cleanup must not fail
/// the run).
async fn delete_bucket(client: &aws_sdk_s3::Client, bucket: &str) {
    let Ok(listed) = client.list_objects_v2().bucket(bucket).send().await else {
        return;
    };
    for object in listed.contents() {
        if let Some(key) = object.key() {
            let _ = client.delete_object().bucket(bucket).key(key).send().await;
        }
    }
    let _ = client.delete_bucket().bucket(bucket).send().await;
}

/// The three containers a [`TestCtx::containers`] run owns.
/// Dropping this struct stops and removes them (testcontainers).
/// The fields are never read — they exist only to own the
/// containers until the struct drops.
#[allow(dead_code)]
pub struct Containers {
    pg: ContainerAsync<GenericImage>,
    redis: ContainerAsync<GenericImage>,
    minio: ContainerAsync<GenericImage>,
    /// Postgres URL of the container's `pf` database (the base the
    /// per-test scratch DB is created from).
    pub pg_base_url: String,
    /// Redis URL of the container.
    pub redis_url: String,
    /// MinIO endpoint URL of the container.
    pub s3_endpoint: String,
}

/// Start postgres:16, redis:7 and quay.io/minio/minio in testcontainers.
/// Docker only — callers env-gate it (`PF_TEST_CONTAINERS=1`).
/// Same images + wait conditions as the api harness used to carry
/// inline; the definitions now live here, once.
pub async fn start_containers() -> Result<Containers, testcontainers::TestcontainersError> {
    use testcontainers::core::{IntoContainerPort, WaitFor};

    let pg = GenericImage::new("postgres", "16")
        .with_exposed_port(5432.tcp())
        .with_wait_for(WaitFor::message_on_stdout(
            "database system is ready to accept connections",
        ))
        .with_env_var("POSTGRES_USER", "pf")
        .with_env_var("POSTGRES_PASSWORD", "pf")
        .with_env_var("POSTGRES_DB", "pf")
        .start()
        .await?;
    let pg_port = pg.get_host_port_ipv4(5432).await?;
    let pg_base_url = format!("postgres://pf:pf@127.0.0.1:{pg_port}/pf");

    let redis = GenericImage::new("redis", "7")
        .with_exposed_port(6379.tcp())
        .with_wait_for(WaitFor::message_on_stdout("Ready to accept connections"))
        .start()
        .await?;
    let redis_port = redis.get_host_port_ipv4(6379).await?;

    let minio = GenericImage::new("quay.io/minio/minio", "latest")
        .with_exposed_port(9000.tcp())
        .with_wait_for(WaitFor::message_on_stdout("API: http://"))
        .with_env_var("MINIO_ROOT_USER", "minioadmin")
        .with_env_var("MINIO_ROOT_PASSWORD", "minioadmin")
        .with_cmd(["server", "/data"])
        .start()
        .await?;
    let minio_port = minio.get_host_port_ipv4(9000).await?;

    Ok(Containers {
        pg,
        redis,
        minio,
        pg_base_url,
        redis_url: format!("redis://127.0.0.1:{redis_port}"),
        s3_endpoint: format!("http://127.0.0.1:{minio_port}"),
    })
}

/// The shared test context: one per test.
pub struct TestCtx {
    /// Postgres URL of the migrated scratch database.
    pub database_url: String,
    /// The scratch database name (for diagnostics; `close` drops it).
    pub database_name: String,
    /// Pool on the scratch database.
    pub pool: DbPool,
    /// Redis URL.
    pub redis_url: String,
    /// Redis key namespace for this test (prefix every key with it).
    pub redis_prefix: String,
    /// S3 endpoint URL.
    pub s3_endpoint: String,
    /// S3 bucket for this test (created when `s3_ready`).
    pub s3_bucket: String,
    /// Whether the bucket exists (false when MinIO is absent, e.g.
    /// the native stack on this VM — the ctx still builds).
    pub s3_ready: bool,
    /// S3 access key (the endpoint's credentials).
    pub s3_access_key: String,
    /// S3 secret key.
    pub s3_secret_key: String,
    /// Base Postgres URL the scratch DB was created from (for
    /// `close`'s DROP).
    admin_url: String,
    /// Owned only so the containers live until `close` drops the
    /// ctx (their Drop stops + removes them); never read.
    #[allow(dead_code)]
    containers: Option<Containers>,
}

impl TestCtx {
    /// Build the context from explicit service URLs: create + migrate
    /// the scratch DB, create the bucket (retrying `bucket_attempts`
    /// times; 0 skips it). Shared by [`TestCtx::new`] and
    /// [`TestCtx::containers`].
    async fn from_urls(
        pg_base_url: &str,
        redis_url: String,
        s3_endpoint: String,
        s3_access_key: String,
        s3_secret_key: String,
        bucket_attempts: u32,
        containers: Option<Containers>,
    ) -> Self {
        let database_name = test_database_name();
        let database_url = replace_database(pg_base_url, &database_name);
        create_database(pg_base_url, &database_name).await;
        let pool = connect_lazy(&database_url, &PoolConfig::default())
            .expect("testkit: scratch pool builds");
        migrate_up(&pool, &migrations_dir())
            .await
            .expect("testkit: migrations apply to the scratch DB");
        let s3_bucket = test_bucket_name();
        let s3_ready = if bucket_attempts == 0 {
            false
        } else {
            ensure_bucket(
                &s3_endpoint,
                &s3_access_key,
                &s3_secret_key,
                &s3_bucket,
                bucket_attempts,
            )
            .await
        };
        Self {
            database_url,
            database_name,
            pool,
            redis_url,
            redis_prefix: test_redis_prefix(),
            s3_endpoint,
            s3_bucket,
            s3_ready,
            s3_access_key,
            s3_secret_key,
            admin_url: pg_base_url.to_string(),
            containers,
        }
    }

    /// Context from the environment: native services on this VM,
    /// compose in CI. The bucket is best-effort (5 attempts —
    /// MinIO is absent on this VM, so this returns promptly with
    /// `s3_ready == false` and the ctx still builds).
    pub async fn new() -> Self {
        let defaults = Settings::default();
        let env_or = |name: &str, fallback: &str| {
            std::env::var(name).unwrap_or_else(|_| fallback.to_string())
        };
        Self::from_urls(
            &env_or("PF_DATABASE_URL", &defaults.database_url),
            env_or("PF_REDIS_URL", &defaults.redis_url),
            env_or("PF_S3_ENDPOINT", &defaults.s3_endpoint),
            env_or("PF_S3_ACCESS_KEY", &defaults.s3_access_key),
            env_or("PF_S3_SECRET_KEY", &defaults.s3_secret_key),
            5,
            None,
        )
        .await
    }

    /// Context from testcontainers: postgres:16, redis:7 and
    /// quay.io/minio/minio start first (docker only — callers env-gate it
    /// on `PF_TEST_CONTAINERS=1`). The bucket IS created here, so
    /// `s3_ready` is true; a failure to create it panics (in this
    /// mode MinIO is promised).
    pub async fn containers() -> Result<Self, testcontainers::TestcontainersError> {
        let started = start_containers().await?;
        let ctx = Self::from_urls(
            &started.pg_base_url.clone(),
            started.redis_url.clone(),
            started.s3_endpoint.clone(),
            "minioadmin".to_string(),
            "minioadmin".to_string(),
            20,
            Some(started),
        )
        .await;
        assert!(
            ctx.s3_ready,
            "testkit: bucket {} must be creatable on the MinIO container",
            ctx.s3_bucket
        );
        Ok(ctx)
    }

    /// Redis key for `name` inside this test's namespace.
    pub fn redis_key(&self, name: &str) -> String {
        format!("{}{}", self.redis_prefix, name)
    }

    /// Whether the S3 bucket exists and is usable.
    pub fn s3_ready(&self) -> bool {
        self.s3_ready
    }

    /// A raw S3 client pointed at this ctx's endpoint + credentials
    /// (for tests that need bucket-level setup beyond the ctx).
    pub fn s3_client(&self) -> aws_sdk_s3::Client {
        s3_client(&self.s3_endpoint, &self.s3_access_key, &self.s3_secret_key)
    }

    /// Tear down: delete the bucket's objects + the bucket
    /// (best-effort), close the pool, drop the scratch database.
    /// Consumes the ctx — the containers (if any) stop when the
    /// struct drops at the end of this call.
    pub async fn close(self) {
        if self.s3_ready {
            delete_bucket(&self.s3_client(), &self.s3_bucket).await;
        }
        self.pool.close().await;
        drop_database(&self.admin_url, &self.database_name).await;
    }
}

