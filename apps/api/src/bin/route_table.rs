//! Print the route table as Markdown (P0-074).
//!
//! The single source is `detag_api::routes::ROUTE_TABLE` — the
//! same table the route-table test probes. Used by `just
//! route-table` (write `docs/api/route-table.md`) and `just
//! route-table-check` (fail on drift); never edit the committed
//! Markdown by hand.
//!
//! Liveness is derived, not stored: `/healthz` and `/readyz` are
//! the only real handlers (meta.rs); every other entry is the
//! shared 501 stub (`PF-5004`) until its Phase ticket lands a
//! real handler. When a Phase ticket lands a handler, this
//! generator must learn liveness from a marker on the table
//! (or from the router) — the route-table test already
//! special-cases the same two paths, so the two stay in sync
//! until then.

use detag_api::routes::ROUTE_TABLE;

/// The only live routes: the meta handlers. Everything else is
/// the 501 stub until its Phase ticket lands.
fn is_live(path: &str) -> bool {
    matches!(path, "/healthz" | "/readyz")
}

fn main() {
    let live = ROUTE_TABLE.iter().filter(|(_, p)| is_live(p)).count();
    let stubs = ROUTE_TABLE.len() - live;
    println!("# Route table");
    println!();
    println!(
        "Generated by `just route-table` from `detag_api::routes::ROUTE_TABLE` — never edit by hand. The order follows the source table (auth, uploads, jobs, billing, admin, meta). Every entry resolves on the built router (see `apps/api/tests/route_table.rs`); the two meta routes are live handlers, everything else is the shared 501 stub (`PF-5004`, `AppError::NotImplemented`) until its Phase ticket lands a real handler. How to add a route: `docs/04-ENGINEERING/04-adding-an-endpoint.md`."
    );
    println!();
    println!("{} routes: {live} live, {stubs} stubs.", ROUTE_TABLE.len());
    println!();
    println!("| Method | Path | Status |");
    println!("| ------ | ---- | ------ |");
    for (method, path) in ROUTE_TABLE {
        let status = if is_live(path) {
            "live".to_string()
        } else {
            "stub — 501 `PF-5004`".to_string()
        };
        println!("| {method} | `{path}` | {status} |");
    }
}
