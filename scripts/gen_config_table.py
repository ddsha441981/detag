#!/usr/bin/env python3
"""Generate the PF_* settings reference table (P0-024, NFR-52).

Reads the sources of truth and writes
docs/06-DELIVERY/04-config-reference.md:
  - name + default (dev) come from .env.example (the committed dev
    defaults; `just env-check` already guarantees .env.example agrees
    with the code and the runbook);
  - used-by comes from the runbook env table
    (docs/06-DELIVERY/03-deploy-runbook.md, "Environment variables").

Fails (exit 1) when .env.example and the runbook drift:
  - a var in .env.example with no runbook row (no used-by), or
  - a var in a runbook row missing from .env.example.

Runbook shorthand understood (same rules as scripts/env_check.py):
  - comma groups: one row may list several vars, all sharing the row's
    used-by (e.g. the PF_S3_* row);
  - slash groups: PF_RESULTS_TTL_FREE/PRO/BUSINESS_H expands to three vars;
  - star patterns (e.g. PF_RATELIMIT_*) are not concrete vars and are skipped.

Usage:
  gen_config_table.py [--check] [--example PATH] [--runbook PATH] [--out PATH]
  --check: generate to memory and fail if the committed file differs
           (drift test); writes nothing.
Defaults: .env.example, docs/06-DELIVERY/03-deploy-runbook.md,
          docs/06-DELIVERY/04-config-reference.md.
Exit 0 on success, 1 on drift.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from env_check import VAR_RE, expand_slash_group  # noqa: E402

HEADER = """# Config reference — PF_* settings (generated)

> Generated by `scripts/gen_config_table.py` (`just gen-config-table`).
> Do not edit by hand — `just config-table-check` (and CI) fail when this
> table differs from `.env.example` + the runbook env table.
> Defaults are local-dev values from `.env.example`; production values come
> from the deployment environment — see `docs/06-DELIVERY/03-deploy-runbook.md`.

| Name | Default (dev) | Used by |
| --- | --- | --- |
"""

TABLE_ROW = "| `{name}` | {default} | {used_by} |\n"


def parse_example_defaults(path: Path) -> dict[str, str]:
    """KEY -> VALUE for PF_* lines in an .env file (comments ignored)."""
    defaults: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        if key.startswith("PF_"):
            defaults[key] = value.strip()
    return defaults


def _row_vars(cell: str) -> set[str]:
    """PF_* vars in one runbook var-cell (slash groups expanded, `*` skipped)."""
    found: set[str] = set()
    for match in VAR_RE.finditer(cell):
        token = match.group(0).rstrip("_/")
        if match.end() < len(cell) and cell[match.end()] == "*":
            continue  # pattern, not a concrete var
        if "/" in token:
            found |= expand_slash_group(token)
        else:
            found.add(token)
    return found


def runbook_used_by(path: Path) -> dict[str, str]:
    """PF_* var -> 'Used by' cell, from the runbook env table."""
    text = path.read_text(encoding="utf-8")
    start = text.find("## Environment variables")
    if start < 0:
        raise ValueError(f"no '## Environment variables' section in {path}")
    end = text.find("\n## ", start + 1)
    section = text[start : end if end > 0 else len(text)]
    used_by: dict[str, str] = {}
    for line in section.splitlines():
        line = line.strip()
        if not line.startswith("|"):
            continue
        cells = [cell.strip() for cell in line.strip("|").split("|")]
        if len(cells) < 2 or cells[0] == "Var" or set(cells[0]) <= {"-", " "}:
            continue  # header row or separator row
        for var in _row_vars(cells[0]):
            used_by[var] = cells[1]
    return used_by


def generate(
    example_path: Path, runbook_path: Path
) -> tuple[str, list[str]]:
    """Return (markdown, errors) for the settings table."""
    defaults = parse_example_defaults(example_path)
    used_by = runbook_used_by(runbook_path)

    errors: list[str] = []
    no_used_by = sorted(set(defaults) - set(used_by))
    if no_used_by:
        errors.append(
            "in .env.example but with no runbook row (no used-by): "
            + ", ".join(no_used_by)
        )
    no_default = sorted(set(used_by) - set(defaults))
    if no_default:
        errors.append(
            "in the runbook but missing from .env.example: "
            + ", ".join(no_default)
        )
    if errors:
        return "", errors

    lines = [HEADER]
    for name in sorted(defaults):
        default = defaults[name]
        rendered = f"`{default}`" if default else "(empty)"
        lines.append(
            TABLE_ROW.format(name=name, default=rendered, used_by=used_by[name])
        )
    return "".join(lines), []


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail if the committed file differs; write nothing")
    parser.add_argument("--example", default=".env.example")
    parser.add_argument(
        "--runbook", default="docs/06-DELIVERY/03-deploy-runbook.md"
    )
    parser.add_argument(
        "--out", default="docs/06-DELIVERY/04-config-reference.md"
    )
    args = parser.parse_args(argv)

    example_path = Path(args.example)
    runbook_path = Path(args.runbook)
    out_path = Path(args.out)

    # The three-way drift guard (example vs runbook vs code) is env-check's
    # job; this generator only needs example + runbook to agree.
    if not example_path.exists():
        print(f"gen-config-table FAIL: no such file: {example_path}")
        return 1

    markdown, errors = generate(example_path, runbook_path)
    if errors:
        for error in errors:
            print(f"gen-config-table FAIL: {error}")
        return 1
    if args.check:
        if not out_path.exists():
            print(f"gen-config-table FAIL: no committed table at {out_path}")
            return 1
        committed = out_path.read_text(encoding="utf-8")
        if committed != markdown:
            print(
                f"gen-config-table FAIL: {out_path} is stale — "
                "run `just gen-config-table` to regenerate"
            )
            return 1
        print("gen-config-table: OK — committed table matches .env.example + runbook")
        return 0
    out_path.write_text(markdown, encoding="utf-8")
    print(f"gen-config-table: wrote {out_path} ({markdown.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
